import assert from 'node:assert/strict';
import { 请求优选API, 获取优选订阅生成器数据, 生成随机IP } from '../src/proxy/preferred.js';
const original = globalThis.fetch;
const url = 'https://source.example/private?token=DO-NOT-EXPOSE';
try {
  globalThis.fetch = async () => new Response('remote error', { status: 503 });
  let result = await 请求优选API([url]);
  assert.equal(result[4][0].state, 'http_error');
  assert.equal(result[4][0].message, '远端返回 HTTP 503');
  assert.equal(result[0].length, 0);
  assert.ok(!JSON.stringify(result[4]).includes('DO-NOT-EXPOSE'));
  assert.ok(!JSON.stringify(result[4]).includes('source.example'));
  const generatorFailure = await 获取优选订阅生成器数据('sub://source.example');
  assert.deepEqual(generatorFailure[0], [], '失败不能返回 127.0.0.1 假节点');
  assert.equal(generatorFailure[2].state, 'http_error');
  const fallback = await 生成随机IP({ url:'https://worker.example/sub' }, 2, 443);
  assert.equal(fallback[0].length, 2); assert.equal(fallback[2].state, 'fallback');
  globalThis.fetch = async () => new Response('');
  assert.equal((await 请求优选API([url]))[4][0].state, 'empty');
  globalThis.fetch = async () => new Response('<html>not a list</html>');
  assert.equal((await 请求优选API([url]))[4][0].state, 'parse_error');
  globalThis.fetch = async () => new Response('1.1.1.1:8443#one\n2606:4700::1#two\ninvalid/path');
  result = await 请求优选API([url]);
  assert.deepEqual(result[0], ['1.1.1.1:8443#one','[2606:4700::1]:443#two']);
  assert.equal(result[4][0].state, 'partial');
  globalThis.fetch = async () => new Response('IP地址,端口,数据中心,TLS\n1.1.1.1,443,HKG,true\n2.2.2.2,80,LAX,false');
  assert.deepEqual((await 请求优选API([url]))[0], ['1.1.1.1:443#HKG']);
  globalThis.fetch = async () => new Response('IP,延迟,下载速度\n1.1.1.1,12,30');
  assert.deepEqual((await 请求优选API([url + '&port=8443']))[0], ['1.1.1.1:8443#CF优选 12ms 30MB/s']);
  globalThis.fetch = async () => new Response(Buffer.concat([Buffer.from('1.1.1.1:443#'),Buffer.from('b1b1bea9','hex')]), {headers:{'Content-Type':'text/plain;charset=gb2312'}});
  assert.deepEqual((await 请求优选API([url + '&proxyip=true#API']))[0], ['1.1.1.1:443#北京 [API]']);
  assert.deepEqual((await 请求优选API([url + '&proxyip=true']))[3], ['1.1.1.1:443']);
  globalThis.fetch = async () => new Response(btoa('vless://example@node.example:443?type=ws'));
  assert.equal((await 请求优选API([url + '#API']))[1][0], 'vless://example@node.example:443?type=ws#%5BAPI%5D', '外部链接备注分隔符必须保留为 #');
  globalThis.fetch = async () => new Response(btoa('vless://00000000-0000-4000-8000-000000000000@1.1.1.1:443?host=example.com#one'));
  const generator = await 获取优选订阅生成器数据('sub://source.example');
  assert.deepEqual(generator[0], ['1.1.1.1:443#one']); assert.equal(generator[2].state,'ok');
  globalThis.fetch = async () => new Response(btoa('vless://00000000-0000-4000-8000-000000000000@999.999.999.999:99999?host=example.com#bad'));
  const invalidGenerator = await 获取优选订阅生成器数据('sub://source.example');
  assert.deepEqual(invalidGenerator[0], [], '生成器非法入口不得标为可用');
  assert.equal(invalidGenerator[2].state, 'parse_error');
  globalThis.fetch = async () => new Response(btoa('vless://00000000-0000-4000-8000-000000000000@[2606:4700:0:0:0:0:0:1]:8443?host=example.com#good'));
  assert.deepEqual((await 获取优选订阅生成器数据('sub://source.example'))[0], ['[2606:4700::1]:8443#good']);
  globalThis.fetch = async (_url, options) => new Response(new ReadableStream({start(controller) {
    options.signal.addEventListener('abort', () => controller.error(Object.assign(new Error('aborted'), {name:'AbortError'})), {once:true});
  }}));
  assert.equal((await 请求优选API([url], '443', 10))[4][0].state, 'timeout', '响应体卡住也应超时');
  globalThis.fetch = async () => new Response(new Uint8Array(512*1024+1));
  assert.equal((await 请求优选API([url]))[4][0].state, 'too_large');
  let redirects = 0;
  globalThis.fetch = async () => { redirects++; return new Response(null, {status:302,headers:{location:'/again'}}); };
  assert.equal((await 请求优选API([url]))[4][0].state,'redirect_limit'); assert.equal(redirects,3);
  let active = 0, maxActive = 0;
  globalThis.fetch = async () => { active++;maxActive=Math.max(active,maxActive);await new Promise(r=>setTimeout(r,5));active--;return new Response('1.1.1.1'); };
  result = await 请求优选API(Array.from({length:10},(_,i)=>'https://source'+i+'.example'));
  assert.equal(result[4].length,10);assert.ok(maxActive<=4,'远端来源并发不超过 4');
  assert.equal((await 获取优选订阅生成器数据(null))[2].state,'invalid_url');
  globalThis.fetch = async () => { throw new Error('network failure with secret token'); };
  const network = (await 请求优选API([url]))[4][0];
  assert.equal(network.state,'network_error'); assert.ok(!JSON.stringify(network).includes('secret'));
  console.log('[test-preferred] HTTP/空列表/解析/慢响应体/大小/重定向/并发限制/脱敏/兜底通过');
} finally { globalThis.fetch = original; }
