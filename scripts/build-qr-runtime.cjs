'use strict';
const fs = require('node:fs');
const path = require('node:path');
const { buildSync } = require('esbuild');
const ROOT = path.resolve(__dirname, '..');
const OUTPUT = path.join(ROOT, 'src/admin/qr.js');

function expectedQrModule() {
  const js = buildSync({ absWorkingDir: ROOT, entryPoints: ['browser/qr.js'], bundle: true, write: false,
    platform: 'browser', format: 'iife', target: 'es2022', minify: true, legalComments: 'none', charset: 'utf8' }).outputFiles[0].text;
  if (js.includes('</script>')) throw new Error('二维码运行时含 HTML script 结束标记');
  return '// Generated by scripts/build-qr-runtime.cjs. Do not edit.\n' +
    'const 二维码运行时 = ' + JSON.stringify(js) + ';\nexport { 二维码运行时 };\n';
}
function checkQrModule() {
  if (!fs.existsSync(OUTPUT) || fs.readFileSync(OUTPUT, 'utf8') !== expectedQrModule()) throw new Error('src/admin/qr.js 与二维码浏览器源码不一致；运行 npm run build');
}
function writeQrModule() { fs.writeFileSync(OUTPUT, expectedQrModule()); }
if (require.main === module) writeQrModule();
module.exports = { checkQrModule, writeQrModule };
